const assert = require('assert');
const qg = require('../src/js/hymt-quality-guard-core');

describe('hymt-quality-guard-core', () => {
    it('flags blank / under as miss', () => {
        const blank = qg.assessHyMtCueQuality('…', 'うちの会社さ、実は');
        assert.strictEqual(blank.ok, false);
        assert.ok(blank.reasons.includes('blank') || blank.reasons.includes('blankish'));
        assert.ok(blank.severity === 'miss' || blank.severity === 'both');

        const under = qg.assessHyMtCueQuality('嗯', '検査室に呼び出された理由を教えてください');
        assert.strictEqual(under.ok, false);
        assert.ok(under.reasons.some((r) => /under|blank/.test(r)));
    });

    it('flags plot invent / adult invent as wrong', () => {
        const invent = qg.assessHyMtCueQuality(
            '检查室里发生的一切都是我的错，请原谅老师和同学们',
            'うん',
        );
        assert.strictEqual(invent.ok, false);
        assert.ok(
            invent.reasons.includes('plot_invent')
            || invent.reasons.includes('balloon')
            || invent.reasons.includes('topic_miss'),
            invent.reasons.join(','),
        );
    });

    it('does not false-flag translated loanwords or 先生 kept as-is', () => {
        assert.strictEqual(
            qg.assessHyMtCueQuality('手机也不可以不交出来吧？', 'スマホも 預けないダメだろ?').ok,
            true,
        );
        assert.strictEqual(
            qg.assessHyMtCueQuality('先生也可以吗？', '先生もいいですか?').ok,
            true,
        );
        assert.strictEqual(
            qg.assessHyMtCueQuality('不好意思 您还好吗？', 'すみません 大丈夫?').ok,
            true,
        );
    });

    it('flags hard number miss and multi-lemma miss', () => {
        const num = qg.assessHyMtCueQuality('我们明天再见面吧', '明日の3時に会いましょう');
        assert.strictEqual(num.ok, false);
        assert.ok(num.reasons.includes('anchor_miss'), num.reasons.join(','));
    });

    it('allows moan JA left as ellipsis', () => {
        const moan = qg.assessHyMtCueQuality('…', 'あぁん');
        assert.strictEqual(moan.ok, true);
        assert.strictEqual(qg.assessHyMtCueQuality('啊 呀呀', 'あっ やっやぁやぁ').ok, true);
        assert.strictEqual(qg.assessHyMtCueQuality('咳咳', 'ごほっ ごほっ').ok, true);
        assert.strictEqual(qg.assessHyMtCueQuality('…', 'ちゅーちゅー').ok, true);
    });

    it('passes faithful short dialogue', () => {
        const ok = qg.assessHyMtCueQuality('早上好', 'おはようございます');
        assert.strictEqual(ok.ok, true, ok.reasons?.join(','));
        const ok2 = qg.assessHyMtCueQuality('没事的', '大丈夫だよ');
        assert.strictEqual(ok2.ok, true, ok2.reasons?.join(','));
    });

    it('collectHyMtQualityRetryIndexes skips moan blanks and credit lines', () => {
        const src = [
            { index: 1, text: 'うちの会社さ' },
            { index: 2, text: 'はぁ' },
            { index: 3, text: 'Subtitles generated by Transub' },
            { index: 4, text: 'おはようございます' },
        ];
        const zh = [
            { index: 1, text: '…' },
            { index: 2, text: '…' },
            { index: 3, text: '…' },
            { index: 4, text: '早上好' },
        ];
        const { indexes } = qg.collectHyMtQualityRetryIndexes(src, zh);
        assert.ok(indexes.includes(1));
        assert.ok(!indexes.includes(2), 'moan ellipsis should skip');
        assert.ok(!indexes.includes(3), 'credit should skip');
        assert.ok(!indexes.includes(4), 'faithful greeting should pass');
    });

    it('qualityRetryHint distinguishes miss vs wrong', () => {
        assert.match(qg.qualityRetryHint({ qualityReasons: ['blank'] }), /漏译/);
        assert.match(qg.qualityRetryHint({ qualityReasons: ['plot_invent'] }), /错译|臆造/);
    });
});
