/**
 * Encode / decode opaque AV maker-prefix payload (known 番号厂牌前缀).
 *
 * Format: magic "AM01" + XOR(zlib.deflate(JSON utf8))
 * Key is fixed in encoder/decoder (obscurity only — not cryptographic secrecy).
 *
 * Usage:
 *   node tools/encode-av-makers.js --from=path/to/av-makers.src.json
 *   node tools/encode-av-makers.js --decode
 *   node tools/encode-av-makers.js --decode --out=path/to/av-makers.src.json
 *
 * Source JSON shape:
 *   {
 *     "v": 1,
 *     "updated": "YYYY-MM-DD",
 *     "sources": ["…"],
 *     "makers": ["ssis", "midv", …]
 *   }
 */
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');

const root = path.join(__dirname, '..');
const DEFAULT_OUT = path.join(root, 'src', 'js', 'av-makers.am1');
const DEFAULT_EMBED = path.join(root, 'src', 'js', 'av-makers-embed.js');
const MAGIC = Buffer.from('AM01');
const XOR_KEY = Buffer.from('TransubAvMakers01');

function xorBuffer(buf, key) {
    const out = Buffer.alloc(buf.length);
    for (let i = 0; i < buf.length; i++) out[i] = buf[i] ^ key[i % key.length];
    return out;
}

function normalizeMakers(list) {
    const out = new Set();
    for (const raw of Array.isArray(list) ? list : []) {
        const p = String(raw || '').trim().toLowerCase();
        if (!/^[a-z][a-z0-9]{1,5}$/.test(p)) continue;
        out.add(p);
    }
    return [...out].sort();
}

function encodePayload(payload) {
    const body = {
        v: Number(payload.v) || 1,
        updated: String(payload.updated || '').trim() || new Date().toISOString().slice(0, 10),
        sources: Array.isArray(payload.sources) ? payload.sources.map(String) : [],
        makers: normalizeMakers(payload.makers),
    };
    const json = Buffer.from(JSON.stringify(body), 'utf8');
    const compressed = zlib.deflateSync(json, { level: 9 });
    return { encoded: Buffer.concat([MAGIC, xorBuffer(compressed, XOR_KEY)]), body };
}

/**
 * Renderer-safe sync loader (no fs / zlib). XOR-only payload of { makers: [...] }.
 */
function buildEmbedJs(body) {
    const slim = { makers: normalizeMakers(body.makers) };
    const xored = xorBuffer(Buffer.from(JSON.stringify(slim), 'utf8'), XOR_KEY);
    const b64 = xored.toString('base64');
    return [
        '/** Auto-generated by tools/encode-av-makers.js — do not edit. Opaque AV maker prefixes. */',
        '(function (global) {',
        '    var KEY = "TransubAvMakers01";',
        `    var B64 = ${JSON.stringify(b64)};`,
        '    function xorDecode(b64, key) {',
        '        var bin = (typeof Buffer !== "undefined")',
        '            ? Buffer.from(b64, "base64")',
        '            : Uint8Array.from(atob(b64), function (c) { return c.charCodeAt(0); });',
        '        var out = new Uint8Array(bin.length);',
        '        for (var i = 0; i < bin.length; i++) out[i] = bin[i] ^ key.charCodeAt(i % key.length);',
        '        var text = (typeof TextDecoder !== "undefined")',
        '            ? new TextDecoder("utf-8").decode(out)',
        '            : (typeof Buffer !== "undefined" ? Buffer.from(out).toString("utf8") : "");',
        '        return JSON.parse(text);',
        '    }',
        '    global.__TRANSUB_LOAD_AV_MAKERS__ = function () {',
        '        try {',
        '            var payload = xorDecode(B64, KEY);',
        '            return Array.isArray(payload && payload.makers) ? payload.makers : [];',
        '        } catch (_) { return []; }',
        '    };',
        '})(typeof globalThis !== "undefined" ? globalThis : typeof window !== "undefined" ? window : this);',
        '',
    ].join('\n');
}

function decodeBuffer(buf) {
    if (!Buffer.isBuffer(buf) || buf.length < 5) {
        throw new Error('av-makers: empty or truncated payload');
    }
    if (buf.subarray(0, 4).toString('utf8') !== 'AM01') {
        throw new Error('av-makers: bad magic');
    }
    const inflated = zlib.inflateSync(xorBuffer(buf.subarray(4), XOR_KEY));
    const payload = JSON.parse(inflated.toString('utf8'));
    if (!payload || typeof payload !== 'object' || !Array.isArray(payload.makers)) {
        throw new Error('av-makers: invalid JSON payload');
    }
    payload.makers = normalizeMakers(payload.makers);
    return payload;
}

function parseArgs(argv) {
    const out = { from: '', decode: false, outPath: '', embedPath: '' };
    for (const a of argv) {
        if (a === '--decode') out.decode = true;
        else if (a.startsWith('--from=')) out.from = a.slice(7).trim();
        else if (a.startsWith('--out=')) out.outPath = a.slice(6).trim();
        else if (a.startsWith('--embed=')) out.embedPath = a.slice(8).trim();
    }
    return out;
}

function writeOutputs(body, encoded, dest, embedDest) {
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.writeFileSync(dest, encoded);
    fs.mkdirSync(path.dirname(embedDest), { recursive: true });
    fs.writeFileSync(embedDest, buildEmbedJs(body), 'utf8');
    console.log('encoded', body.makers.length, 'makers →', dest, `(${encoded.length} bytes)`);
    console.log('embed →', embedDest);
}

function main() {
    const args = parseArgs(process.argv.slice(2));
    const embedDest = args.embedPath ? path.resolve(args.embedPath) : DEFAULT_EMBED;
    if (args.decode) {
        const raw = fs.readFileSync(DEFAULT_OUT);
        const payload = decodeBuffer(raw);
        const text = `${JSON.stringify(payload, null, 2)}\n`;
        if (args.outPath) {
            fs.mkdirSync(path.dirname(path.resolve(args.outPath)), { recursive: true });
            fs.writeFileSync(args.outPath, text, 'utf8');
            console.log('decoded →', args.outPath, `(${payload.makers.length} makers)`);
        } else {
            process.stdout.write(text);
        }
        return;
    }
    if (!args.from) {
        console.error('Usage: node tools/encode-av-makers.js --from=av-makers.src.json');
        console.error('       node tools/encode-av-makers.js --decode [--out=av-makers.src.json]');
        process.exit(1);
    }
    const srcPath = path.resolve(args.from);
    const payload = JSON.parse(fs.readFileSync(srcPath, 'utf8'));
    const { encoded, body } = encodePayload(payload);
    const dest = args.outPath ? path.resolve(args.outPath) : DEFAULT_OUT;
    writeOutputs(body, encoded, dest, embedDest);
}

if (require.main === module) {
    main();
}

module.exports = {
    MAGIC,
    XOR_KEY,
    DEFAULT_OUT,
    DEFAULT_EMBED,
    normalizeMakers,
    encodePayload,
    decodeBuffer,
    buildEmbedJs,
    writeOutputs,
};
