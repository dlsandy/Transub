    /**
     * @param {Record<string, HTMLElement|null|undefined>} els
     * @param {Document} [doc]
     */
    function cacheAppDomElements(els, doc) {
        const target = els && typeof els === 'object' ? els : {};
        const d = doc || (typeof document !== 'undefined' ? document : null);
        if (!d) return target;
        for (const id of APP_ELEMENT_IDS) {
            target[id] = d.getElementById(id);
        }
        target.paramsTabBtns = Array.from(d.querySelectorAll('.params-tab-btn'));
        target.paramsTabPanels = Array.from(d.querySelectorAll('.params-tab-panel'));
        target.postTaskMenuItems = Array.from(d.querySelectorAll('#postTaskMenu .post-task-menu-item'));
        target.addMenuItems = Array.from(d.querySelectorAll('[data-add-action]'));
        target.clearListMenuItems = Array.from(d.querySelectorAll('#clearListMenu [data-clear-action]'));
        return target;
    }

    return {
        APP_ELEMENT_IDS,
        cacheAppDomElements,
    };
